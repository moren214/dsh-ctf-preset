export function templateSource(kind) {
  if (typeof kind !== 'string' || !Object.hasOwn(CRYPTO_TEMPLATES, kind)) {
    throw new ToolError('unsupported', `未知模板：${kind}。`);
  }
  return CRYPTO_TEMPLATES[kind];
}
